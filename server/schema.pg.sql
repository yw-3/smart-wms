# ===== 智能物料仓储系统 · 数据表结构（PostgreSQL / Supabase）=====
# 用法：Supabase 控制台 → SQL Editor → 新建查询 → 粘贴本文件 → Run
# 说明：
#   - 全部为幂等建表（IF NOT EXISTS），可重复执行
#   - 时间列用 TEXT 存 'YYYY-MM-DD HH:MM:SS'（UTC），与 SQLite 版本格式一致
#   - 自增主键用 IDENTITY，兼容应用层的 lastInsertRowid 语义

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  real_name TEXT,
  role TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  failed_attempts INTEGER DEFAULT 0,
  locked_until INTEGER DEFAULT 0,
  must_change_pwd INTEGER DEFAULT 0,
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS suppliers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  contact TEXT,
  phone TEXT,
  address TEXT,
  status TEXT DEFAULT 'active',
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS locations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,
  name TEXT,
  type TEXT,
  description TEXT,
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS units (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  main_unit TEXT NOT NULL,
  sub_unit TEXT,
  factor REAL,
  note TEXT
);

CREATE TABLE IF NOT EXISTS materials (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  spec TEXT,
  category TEXT,
  remark TEXT,
  barcode TEXT,
  unit_main TEXT,
  unit_sub TEXT,
  unit_factor REAL,
  abc_class TEXT DEFAULT 'C',
  supplier_id INTEGER,
  location_id INTEGER,
  safety_stock REAL DEFAULT 0,
  status TEXT DEFAULT 'active',
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  updated_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  FOREIGN KEY(supplier_id) REFERENCES suppliers(id),
  FOREIGN KEY(location_id) REFERENCES locations(id)
);

CREATE TABLE IF NOT EXISTS operation_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER,
  username TEXT,
  real_name TEXT,
  action TEXT,
  module TEXT,
  detail TEXT,
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS inbound_orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no TEXT UNIQUE NOT NULL,
  material_code TEXT NOT NULL,
  material_name TEXT,
  qty REAL NOT NULL,
  batch_no TEXT,
  prod_date TEXT,
  expiry_date TEXT,
  supplier_code TEXT,
  quality_status TEXT DEFAULT '待检',
  location_code TEXT,
  operator_id INTEGER,
  operator_name TEXT,
  status TEXT DEFAULT '已提交',
  remark TEXT,
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  updated_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS batch_inventory (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  material_code TEXT NOT NULL,
  location_code TEXT NOT NULL,
  batch_no TEXT NOT NULL,
  qty REAL DEFAULT 0,
  prod_date TEXT,
  expiry_date TEXT,
  supplier_code TEXT,
  quality_status TEXT DEFAULT '待检',
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  UNIQUE(material_code, location_code, batch_no)
);

CREATE TABLE IF NOT EXISTS stock (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  material_code TEXT NOT NULL,
  location_code TEXT NOT NULL,
  qty_total REAL DEFAULT 0,
  qty_available REAL DEFAULT 0,
  updated_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  UNIQUE(material_code, location_code)
);

CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  spec TEXT,
  unit_main TEXT,
  remark TEXT,
  status TEXT DEFAULT 'active',
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  updated_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS bom (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_code TEXT NOT NULL,
  component_code TEXT NOT NULL,
  qty_per_unit REAL NOT NULL,
  usage_unit TEXT,
  remark TEXT,
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  UNIQUE(product_code, component_code)
);

CREATE TABLE IF NOT EXISTS production_lines (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_no INTEGER UNIQUE NOT NULL,
  name TEXT,
  line_location_code TEXT
);

CREATE TABLE IF NOT EXISTS requisition_orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_no TEXT UNIQUE NOT NULL,
  line_no INTEGER,
  operator_id INTEGER,
  operator_name TEXT,
  source_type TEXT DEFAULT 'BOM',
  status TEXT DEFAULT '已提交',
  remark TEXT,
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  updated_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS requisition_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL,
  material_code TEXT NOT NULL,
  material_name TEXT,
  qty REAL NOT NULL,
  batch_no TEXT,
  prod_date TEXT,
  expiry_date TEXT,
  from_location_code TEXT,
  to_location_code TEXT,
  created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
  FOREIGN KEY(order_id) REFERENCES requisition_orders(id)
);

-- ===== 索引（按查询热点补充）=====
CREATE INDEX IF NOT EXISTS idx_batch_material_loc ON batch_inventory(material_code, location_code);
CREATE INDEX IF NOT EXISTS idx_batch_expiry ON batch_inventory(expiry_date);
CREATE INDEX IF NOT EXISTS idx_inbound_created ON inbound_orders(created_at);
CREATE INDEX IF NOT EXISTS idx_requisition_created ON requisition_orders(created_at);
CREATE INDEX IF NOT EXISTS idx_logs_created ON operation_logs(created_at);
